/*
|--------------------------------------------------------------------------
| Accept POST requests only
|--------------------------------------------------------------------------
*/

if ($_SERVER["REQUEST_METHOD"] !== "POST") {
    header("Location: elections.php");
    exit;
}

/*
|--------------------------------------------------------------------------
| Validate the CSRF token generated by vote.php
|--------------------------------------------------------------------------
*/

$submittedToken = $_POST["csrf_token"] ?? "";
$storedToken = $_SESSION["vote_selection_token"] ?? "";

if (
    !is_string($submittedToken) ||
    !is_string($storedToken) ||
    $storedToken === "" ||
    !hash_equals($storedToken, $submittedToken)
) {
    showSelectionMessage(
        "Session Verification Failed",
        "Your selection could not be verified. Return to the elections page and start or reopen your voting session.",
        "elections.php",
        403
    );
}

/*
|--------------------------------------------------------------------------
| Validate the submitted values
|--------------------------------------------------------------------------
*/

$rawElectionId = $_POST["election_id"] ?? null;
$rawPositionId = $_POST["position_id"] ?? null;
$rawCandidateId = $_POST["candidate_id"] ?? null;
$rawPositionIndex = $_POST["position_index"] ?? null;

if (
    !is_scalar($rawElectionId) ||
    !is_scalar($rawPositionId) ||
    !is_scalar($rawCandidateId) ||
    !is_scalar($rawPositionIndex)
) {
    showSelectionMessage(
        "Invalid Selection",
        "The submitted voting information is invalid."
    );
}

$election_id = filter_var(
    (string)$rawElectionId,
    FILTER_VALIDATE_INT
);

$position_id = filter_var(
    (string)$rawPositionId,
    FILTER_VALIDATE_INT
);

$candidate_id = filter_var(
    (string)$rawCandidateId,
    FILTER_VALIDATE_INT
);

$position_index = filter_var(
    (string)$rawPositionIndex,
    FILTER_VALIDATE_INT,
    ["options" => ["min_range" => 0]]
);

if (
    $election_id === false ||
    $election_id === null ||
    $election_id <= 0 ||
    $position_id === false ||
    $position_id === null ||
    $position_id <= 0 ||
    $candidate_id === false ||
    $candidate_id === null ||
    $candidate_id <= 0 ||
    $position_index === false ||
    $position_index === null
) {
    showSelectionMessage(
        "Invalid Selection",
        "Some voting information is missing or invalid."
    );
}

$election_id = (int)$election_id;
$position_id = (int)$position_id;
$candidate_id = (int)$candidate_id;
$position_index = (int)$position_index;
$voter_id = (int)$_SESSION["user_id"];

/*
|--------------------------------------------------------------------------
| Confirm the voter account is active
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT department, status
    FROM users
    WHERE id = :id
      AND role = 'voter'
    LIMIT 1
");

$stmt->execute(["id" => $voter_id]);
$voter = $stmt->fetch(PDO::FETCH_ASSOC);

if (!$voter || ($voter["status"] ?? "") !== "active") {
    showSelectionMessage(
        "Account Unavailable",
        "Your voter account could not be verified as active. Please contact the administrator.",
        "dashboard.php",
        403
    );
}

$voter_department = trim(
    (string)($voter["department"] ?? "")
);

/*
|--------------------------------------------------------------------------
| Verify the election remains open
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT
        id,
        election_name,
        status,
        start_date,
        end_date,
        eligibility_type,
        eligibility_department
    FROM elections
    WHERE id = :election_id
      AND status = 'active'
      AND NOW() BETWEEN start_date AND end_date
    LIMIT 1
");

$stmt->execute(["election_id" => $election_id]);
$election = $stmt->fetch(PDO::FETCH_ASSOC);

if (!$election) {
    showSelectionMessage(
        "Election Unavailable",
        "This election is no longer open or is outside its scheduled voting period.",
        "elections.php",
        403
    );
}

/*
|--------------------------------------------------------------------------
| Enforce voter eligibility
|--------------------------------------------------------------------------
*/

$eligibility_type = (string)(
    $election["eligibility_type"] ?? ""
);

$is_eligible = false;

if ($eligibility_type === "all") {
    $is_eligible = true;

} elseif ($eligibility_type === "department") {
    $required_department = trim(
        (string)($election["eligibility_department"] ?? "")
    );

    $is_eligible = (
        $required_department !== "" &&
        $voter_department !== "" &&
        strcasecmp(
            $required_department,
            $voter_department
        ) === 0
    );

} elseif ($eligibility_type === "engineering") {
    $engineering_departments = [
        "Computer Engineering",
        "Electrical Engineering",
        "Mechanical Engineering",
        "Civil Engineering",
        "Chemical Engineering",
        "Agricultural Engineering",
        "Electronics Engineering",
        "Mechatronics Engineering"
    ];

    foreach ($engineering_departments as $department) {
        if (
            $voter_department !== "" &&
            strcasecmp($department, $voter_department) === 0
        ) {
            $is_eligible = true;
            break;
        }
    }
}

if (!$is_eligible) {
    showSelectionMessage(
        "Access Denied",
        "Your registered department is not eligible for this election.",
        "elections.php",
        403
    );
}

/*
|--------------------------------------------------------------------------
| Prevent another selection session if votes already exist
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM votes
    WHERE election_id = :election_id
      AND voter_id = :voter_id
    LIMIT 1
");

$stmt->execute([
    "election_id" => $election_id,
    "voter_id" => $voter_id
]);

if ($stmt->fetch(PDO::FETCH_ASSOC)) {
    unset(
        $_SESSION["vote_selections"],
        $_SESSION["vote_election_id"]
    );

    showSelectionMessage(
        "Votes Already Recorded",
        "A vote has already been recorded for your account in this election.",
        "dashboard.php",
        409
    );
}

/*
|--------------------------------------------------------------------------
| Validate position and position index
|--------------------------------------------------------------------------
|
| The ordering must match the ordering used by vote.php.
*/

$stmt = $pdo->query("
    SELECT id, position_name, display_order
    FROM positions
    WHERE status = 'active'
    ORDER BY display_order ASC
");

$positions = $stmt->fetchAll(PDO::FETCH_ASSOC);
$total_positions = count($positions);

if ($total_positions === 0) {
    showSelectionMessage(
        "No Positions Available",
        "There are no active voting positions configured.",
        "elections.php"
    );
}

if ($position_index >= $total_positions) {
    showSelectionMessage(
        "Invalid Position",
        "The submitted position number is invalid.",
        "elections.php"
    );
}

$expected_position_id = (int)$positions[$position_index]["id"];

if ($position_id !== $expected_position_id) {
    showSelectionMessage(
        "Invalid Position",
        "The selected position does not match the current voting step.",
        "elections.php",
        403
    );
}

/*
|--------------------------------------------------------------------------
| Verify the candidate belongs to the election and selected position
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM candidates
    WHERE id = :candidate_id
      AND election_id = :election_id
      AND position_id = :position_id
      AND status = 'active'
    LIMIT 1
");

$stmt->execute([
    "candidate_id" => $candidate_id,
    "election_id" => $election_id,
    "position_id" => $position_id
]);

$candidate = $stmt->fetch(PDO::FETCH_ASSOC);

if (!$candidate) {
    showSelectionMessage(
        "Invalid Candidate",
        "This candidate is not active for the selected election and position. Please select an available candidate.",
        "vote.php?election=" . $election_id,
        409
    );
}

/*
|--------------------------------------------------------------------------
| Prevent selections for a position already recorded in the database
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    SELECT id
    FROM votes
    WHERE election_id = :election_id
      AND voter_id = :voter_id
      AND position_id = :position_id
    LIMIT 1
");

$stmt->execute([
    "election_id" => $election_id,
    "voter_id" => $voter_id,
    "position_id" => $position_id
]);

if ($stmt->fetch(PDO::FETCH_ASSOC)) {
    showSelectionMessage(
        "Vote Already Recorded",
        "A vote has already been recorded for this position.",
        "dashboard.php",
        409
    );
}

/*
|--------------------------------------------------------------------------
| Prepare session selections for this election
|--------------------------------------------------------------------------
*/

$current_session_election = (int)(
    $_SESSION["vote_election_id"] ?? 0
);

if ($current_session_election !== $election_id) {
    $_SESSION["vote_selections"] = [];
    $_SESSION["vote_election_id"] = $election_id;
}

if (
    !isset($_SESSION["vote_selections"]) ||
    !is_array($_SESSION["vote_selections"])
) {
    $_SESSION["vote_selections"] = [];
}

/*
|--------------------------------------------------------------------------
| Save this candidate as a temporary selection
|--------------------------------------------------------------------------
|
| This handler does not insert a vote into the database. Final vote
| recording remains the responsibility of submit_votes.php.
*/

$_SESSION["vote_selections"][$position_id] = $candidate_id;
$_SESSION["vote_election_id"] = $election_id;

/*
 * Rotate the token after a successful selection. vote.php will render
 * the newly stored token on the next page request.
 */
$_SESSION["vote_selection_token"] = bin2hex(random_bytes(32));

/*
|--------------------------------------------------------------------------
| Continue to the next position or the review page
|--------------------------------------------------------------------------
*/

$next_position_index = $position_index + 1;

if ($next_position_index >= $total_positions) {
    header("Location: review_votes.php");
    exit;
}

header(
    "Location: vote.php?election=" .
    $election_id .
    "&position=" .
    $next_position_index
);

exit;
