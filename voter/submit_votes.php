/*
|--------------------------------------------------------------------------
| Accept POST requests only
|--------------------------------------------------------------------------
*/

if ($_SERVER["REQUEST_METHOD"] !== "POST") {
    header("Location: elections.php");
    exit;
}

/*
|--------------------------------------------------------------------------
| Validate the CSRF token generated by review_votes.php
|--------------------------------------------------------------------------
*/

$submittedToken = $_POST["csrf_token"] ?? "";
$storedToken = $_SESSION["submit_votes_token"] ?? "";

if (
    !is_string($submittedToken) ||
    !is_string($storedToken) ||
    $storedToken === "" ||
    !hash_equals($storedToken, $submittedToken)
) {
    showSubmissionMessage(
        "Session Verification Failed",
        "Your submission could not be verified. Return to your voting session and review your selections again.",
        "elections.php",
        403
    );
}

/*
|--------------------------------------------------------------------------
| Validate the temporary voting selections
|--------------------------------------------------------------------------
*/

if (
    !isset($_SESSION["vote_selections"]) ||
    !is_array($_SESSION["vote_selections"]) ||
    !isset($_SESSION["vote_election_id"])
) {
    showSubmissionMessage(
        "No Voting Selections",
        "Your temporary voting selections could not be found. Return to the election and select your candidates again.",
        "elections.php"
    );
}

$voter_id = (int)$_SESSION["user_id"];
$election_id = (int)$_SESSION["vote_election_id"];
$selections = $_SESSION["vote_selections"];

if (
    $voter_id <= 0 ||
    $election_id <= 0 ||
    count($selections) === 0
) {
    showSubmissionMessage(
        "Invalid Voting Session",
        "Your voting session is invalid or contains no selections. Please return to the elections page.",
        "elections.php"
    );
}

try {
    $pdo->beginTransaction();

    /*
    |--------------------------------------------------------------------------
    | Lock and verify the voter account
    |--------------------------------------------------------------------------
    */

    $stmt = $pdo->prepare("
        SELECT id, department, status
        FROM users
        WHERE id = :id
          AND role = 'voter'
        LIMIT 1
        FOR UPDATE
    ");

    $stmt->execute(["id" => $voter_id]);
    $voter = $stmt->fetch(PDO::FETCH_ASSOC);

    if (!$voter || ($voter["status"] ?? "") !== "active") {
        $pdo->rollBack();

        showSubmissionMessage(
            "Account Inactive",
            "Your voter account could not be verified as active. Please contact the administrator.",
            "dashboard.php",
            403
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Lock and verify the election
    |--------------------------------------------------------------------------
    */

    $stmt = $pdo->prepare("
        SELECT
            id,
            election_name,
            status,
            start_date,
            end_date,
            eligibility_type,
            eligibility_department
        FROM elections
        WHERE id = :id
        LIMIT 1
        FOR UPDATE
    ");

    $stmt->execute(["id" => $election_id]);
    $election = $stmt->fetch(PDO::FETCH_ASSOC);

    if (!$election) {
        $pdo->rollBack();

        showSubmissionMessage(
            "Election Not Found",
            "The selected election no longer exists.",
            "elections.php",
            404
        );
    }

    if (
        ($election["status"] ?? "") !== "active" ||
        empty($election["start_date"]) ||
        empty($election["end_date"])
    ) {
        $pdo->rollBack();

        showSubmissionMessage(
            "Election Unavailable",
            "This election is no longer active or its voting schedule is unavailable.",
            "elections.php",
            403
        );
    }

    $timeCheck = $pdo->prepare("
        SELECT NOW() BETWEEN :start_date AND :end_date
    ");

    $timeCheck->execute([
        "start_date" => $election["start_date"],
        "end_date" => $election["end_date"]
    ]);

    if ((int)$timeCheck->fetchColumn() !== 1) {
        $pdo->rollBack();

        showSubmissionMessage(
            "Voting Period Closed",
            "The election is outside its scheduled voting period. Your selections have not been submitted.",
            "elections.php",
            403
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Enforce the election's eligibility rules
    |--------------------------------------------------------------------------
    */

    $voter_department = trim(
        (string)($voter["department"] ?? "")
    );

    $eligibility_type = (string)(
        $election["eligibility_type"] ?? ""
    );

    $is_eligible = false;

    if ($eligibility_type === "all") {
        $is_eligible = true;

    } elseif ($eligibility_type === "department") {
        $required_department = trim(
            (string)($election["eligibility_department"] ?? "")
        );

        $is_eligible = (
            $required_department !== "" &&
            $voter_department !== "" &&
            strcasecmp(
                $required_department,
                $voter_department
            ) === 0
        );

    } elseif ($eligibility_type === "engineering") {
        $engineering_departments = [
            "Computer Engineering",
            "Electrical Engineering",
            "Mechanical Engineering",
            "Civil Engineering",
            "Chemical Engineering",
            "Agricultural Engineering",
            "Electronics Engineering",
            "Mechatronics Engineering"
        ];

        foreach ($engineering_departments as $department) {
            if (
                $voter_department !== "" &&
                strcasecmp($department, $voter_department) === 0
            ) {
                $is_eligible = true;
                break;
            }
        }
    }

    if (!$is_eligible) {
        $pdo->rollBack();

        showSubmissionMessage(
            "Access Denied",
            "Your registered department is not eligible for this election. No votes were submitted.",
            "elections.php",
            403
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Load active positions in the same display order as vote.php
    |--------------------------------------------------------------------------
    */

    $stmt = $pdo->query("
        SELECT id, position_name, display_order
        FROM positions
        WHERE status = 'active'
        ORDER BY display_order ASC
        FOR UPDATE
    ");

    $positions = $stmt->fetchAll(PDO::FETCH_ASSOC);

    if (!$positions) {
        $pdo->rollBack();

        showSubmissionMessage(
            "No Active Positions",
            "There are no active voting positions configured.",
            "elections.php"
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Reject saved selections for missing or inactive positions
    |--------------------------------------------------------------------------
    */

    $activePositionIds = [];

    foreach ($positions as $position) {
        $activePositionIds[] = (int)$position["id"];
    }

    foreach (array_keys($selections) as $savedPositionId) {
        if (
            !is_int($savedPositionId) &&
            !is_string($savedPositionId)
        ) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Invalid Selection",
                "Your voting session contains an invalid position reference. Please review your selections again.",
                "vote.php?election=" . $election_id
            );
        }

        if (
            !ctype_digit((string)$savedPositionId) ||
            !in_array(
                (int)$savedPositionId,
                $activePositionIds,
                true
            )
        ) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Invalid Selection",
                "A saved selection refers to an inactive or invalid position. Please review your selections again.",
                "vote.php?election=" . $election_id
            );
        }
    }

    /*
    |--------------------------------------------------------------------------
    | Require a valid candidate for every active position
    |--------------------------------------------------------------------------
    */

    $validatedVotes = [];

    $checkCandidate = $pdo->prepare("
        SELECT id
        FROM candidates
        WHERE id = :candidate_id
          AND election_id = :election_id
          AND position_id = :position_id
          AND status = 'active'
        LIMIT 1
        FOR UPDATE
    ");

    foreach ($positions as $position) {
        $position_id = (int)$position["id"];

        if (!array_key_exists($position_id, $selections)) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Incomplete Selections",
                "You must select a candidate for every active position before submitting.",
                "vote.php?election=" . $election_id
            );
        }

        $rawCandidateId = $selections[$position_id];

        if (!is_scalar($rawCandidateId)) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Invalid Selection",
                "One of your candidate selections is invalid. Please review your choices again.",
                "vote.php?election=" . $election_id
            );
        }

        $candidate_id = filter_var(
            (string)$rawCandidateId,
            FILTER_VALIDATE_INT,
            ["options" => ["min_range" => 1]]
        );

        if ($candidate_id === false || $candidate_id === null) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Invalid Selection",
                "One of your candidate selections is invalid. Please review your choices again.",
                "vote.php?election=" . $election_id
            );
        }

        $checkCandidate->execute([
            "candidate_id" => (int)$candidate_id,
            "election_id" => $election_id,
            "position_id" => $position_id
        ]);

        if (!$checkCandidate->fetch(PDO::FETCH_ASSOC)) {
            $pdo->rollBack();

            showSubmissionMessage(
                "Candidate Unavailable",
                "One of your selected candidates is no longer active for the relevant position. Please review your choices.",
                "vote.php?election=" . $election_id,
                409
            );
        }

        $validatedVotes[] = [
            "election_id" => $election_id,
            "voter_id" => $voter_id,
            "position_id" => $position_id,
            "candidate_id" => (int)$candidate_id
        ];
    }

    /*
    |--------------------------------------------------------------------------
    | Prevent a second election submission
    |--------------------------------------------------------------------------
    */

    $stmt = $pdo->prepare("
        SELECT id
        FROM votes
        WHERE election_id = :election_id
          AND voter_id = :voter_id
        LIMIT 1
        FOR UPDATE
    ");

    $stmt->execute([
        "election_id" => $election_id,
        "voter_id" => $voter_id
    ]);

    if ($stmt->fetch(PDO::FETCH_ASSOC)) {
        $pdo->rollBack();

        unset(
            $_SESSION["vote_selections"],
            $_SESSION["vote_election_id"]
        );

        showSubmissionMessage(
            "Votes Already Recorded",
            "Votes have already been recorded for your account in this election. Another submission is not permitted.",
            "dashboard.php",
            409
        );
    }

    /*
    |--------------------------------------------------------------------------
    | Insert all votes in one database transaction
    |--------------------------------------------------------------------------
    */

    $insertVote = $pdo->prepare("
        INSERT INTO votes (
            election_id,
            voter_id,
            position_id,
            candidate_id
        ) VALUES (
            :election_id,
            :voter_id,
            :position_id,
            :candidate_id
        )
    ");

    foreach ($validatedVotes as $vote) {
        $insertVote->execute($vote);
    }

    /*
    |--------------------------------------------------------------------------
    | Commit only after every vote has been inserted
    |--------------------------------------------------------------------------
    */

    $pdo->commit();

    unset(
        $_SESSION["vote_selections"],
        $_SESSION["vote_election_id"],
        $_SESSION["submit_votes_token"]
    );

    $_SESSION["vote_completed"] = true;

    header("Location: vote_success.php");
    exit;

} catch (PDOException $exception) {
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }

    error_log(
        "Vote submission database error: " .
        $exception->getMessage()
    );

    $sqlState = (string)$exception->getCode();
    $mysqlError = (int)($exception->errorInfo[1] ?? 0);

    if ($sqlState === "23000" || $mysqlError === 1062) {
        showSubmissionMessage(
            "Submission Not Completed",
            "The database prevented a duplicate or conflicting voting record. Your transaction was rolled back. Check your voting status before trying again.",
            "dashboard.php",
            409
        );
    }

    showSubmissionMessage(
        "Unable to Submit Votes",
        "The system could not complete your submission. Please check your voting status or contact the administrator.",
        "dashboard.php",
        500
    );

} catch (Throwable $exception) {
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }

    error_log(
        "Vote submission error: " .
        $exception->getMessage()
    );

    showSubmissionMessage(
        "Submission Not Completed",
        "An unexpected error prevented submission. Please check your voting status before trying again.",
        "dashboard.php",
        500
    );
}
